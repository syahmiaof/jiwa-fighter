const { chromium, expect } = require('@playwright/test');
const fs = require('fs');
const base = process.argv[2] || 'http://localhost:3000';

(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: {width:1440,height:900} });
  await page.addInitScript(() => sessionStorage.setItem('jiwa-fighter:intro-seen:v1', '1'));
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if(m.type()==='warn' && /GSAP|target/i.test(m.text())) errors.push(m.text()); });
  const checks=[];
  await page.goto(base + '/',{waitUntil:'networkidle'});
  await page.getByRole('button',{name:'Search',exact:true}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.getByRole('dialog').getByRole('textbox')).toBeFocused();
  await page.keyboard.press('Shift+Tab');
  await expect(page.getByRole('button',{name:'Close search'})).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(page.getByRole('dialog').getByRole('textbox')).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Search',exact:true})).toBeFocused();
  checks.push('Search: initial focus, Tab loop, Escape, focus return');
  await page.goto(base + '/products/keris-tuah',{waitUntil:'networkidle'});
  await page.getByRole('button',{name:'M',exact:true}).click();
  await page.getByRole('button',{name:/ADD TO BAG/}).click();
  await expect(page.getByRole('dialog')).toHaveCount(1);
  await expect(page.getByRole('button',{name:'Close cart',exact:true})).toBeFocused();
  await page.getByRole('button',{name:/PROCEED TO CHECKOUT/}).click();
  await expect(page.getByRole('dialog')).toHaveCount(2);
  await expect(page.getByRole('button',{name:'Close dialog',exact:true})).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(1);
  await expect(page.getByRole('button',{name:/PROCEED TO CHECKOUT/})).toBeFocused();
  if(await page.evaluate(()=>document.body.style.overflow)!=='hidden') throw new Error('Nested body lock lost');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('button',{name:/ADD TO BAG/})).toBeFocused();
  if(await page.evaluate(()=>document.body.style.overflow)==='hidden') throw new Error('Body lock leaked');
  checks.push('Cart + nested checkout: focus isolation, independent Escape, stacked scroll lock, focus return');
  await page.goto(base + '/',{waitUntil:'networkidle'});
  await page.waitForTimeout(800);
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.waitForTimeout(150);
  const reduced = await page.locator('.hero-headline,.hero-image,.collection-card').evaluateAll(es=>es.map(e=>({opacity:getComputedStyle(e).opacity,transform:e.style.transform})));
  if(reduced.some(e=>e.opacity!=='1'||e.transform)) throw new Error('Reduced motion did not revert '+JSON.stringify(reduced));
  checks.push('Live reduced-motion switch: hero/cards visible and inline transforms reverted');
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.waitForTimeout(800);
  for(const path of ['/shop','/lookbook','/our-story','/']) {
    await page.locator('header a[href="'+path+'"]').first().click();
    await page.waitForTimeout(700);
  }
  checks.push('Client navigation across Shop, Lookbook, Story, Home without runtime/GSAP warnings');
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Open Shopping Bag'}).click();
  await page.waitForTimeout(350);
  const panel=await page.locator('.drawer-panel').boundingBox();
  if(panel.x<0 || panel.x+panel.width>391) throw new Error('Drawer overflows mobile');
  checks.push('390px mobile drawer remains in viewport');
  fs.mkdirSync('tests/v2',{recursive:true});
  const result={url:base,browser:'Chromium',checks,errors};
  fs.writeFileSync('tests/v2/motion-qa.json',JSON.stringify(result,null,2));
  await browser.close();
  if(errors.length) throw new Error(JSON.stringify(errors));
  console.log(JSON.stringify(result,null,2));
})().catch(e=>{console.error(e);process.exit(1)});
